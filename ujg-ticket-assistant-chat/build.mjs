import {build as esbuild} from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url));
export async function build({write = true} = {}) {
    const result = await esbuild({entryPoints: [path.join(dir, 'runtime.mjs')], bundle: true, write: false,
        platform: 'browser', format: 'iife', globalName: 'pico', target: ['es2022'], minify: true, legalComments: 'inline', metafile: true});
    const notices = '@earendil-works/pi-agent-core 1.4.0 and @earendil-works/pi-ai 1.4.0\n' +
        'Source: https://github.com/earendil-works/pi/tree/v1.4.0\n\n' + fs.readFileSync(path.join(dir, 'licenses/pi-1.4.0.txt'), 'utf8') +
        '\n\ntypebox 1.3.27\n\n' + fs.readFileSync(path.join(dir, 'node_modules/typebox/license'), 'utf8');
    const licensed = new Set(['@earendil-works/pi-agent-core', '@earendil-works/pi-ai', 'typebox']);
    for (const output of Object.values(result.metafile.outputs)) {
        if (output.imports.length) throw Error('Pico browser bundle must not have external imports');
        for (const [input, contribution] of Object.entries(output.inputs)) {
            const dependency = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1];
            if (contribution.bytesInOutput && dependency && !licensed.has(dependency)) throw Error('Missing bundled dependency license: ' + dependency);
        }
    }
    // The bundle lives inside the AMD factory. Neither module registration nor any
    // sibling widget evaluates Pi or assumes process/window/crypto/performance exists.
    const source = '/* Generated by ujg-ticket-assistant-chat/build.mjs.\n' + notices + '\n*/\n' +
        'define("_ujgTA_picoRuntime", [], function() {\n' +
        'var runtime; function load() { if (runtime) return runtime;\n' + result.outputFiles[0].text + '\nruntime = pico; return runtime; }\n' +
        'return {VERSION:"1.4.0", LIMITS:{modelCalls:8,toolCalls:12,wallMs:180000}, createSession:function(options) { return load().createSession(options); }};\n});\n';
    if (write) {
        fs.writeFileSync(path.join(dir, '../vendor/pico-1.4.0.amd.js'), source);
        fs.writeFileSync(path.join(dir, '../vendor/pico-1.4.0.LICENSE.txt'), notices);
    }
    return source;
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    await build();
    console.log('Built isolated Pico AMD runtime (Pi 1.4.0).');
}
