#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
// AMD registers every definition before resolving main; storage depends on draft.
const MODULE_ORDER = ['profiles.js', 'fields.js', 'validation.js', 'draft.js', 'storage.js', 'api.js', 'ai.js', 'controller.js', 'icons.js', 'field-ui.js', 'settings-ui.js', 'ui.js', 'main.js'];
function build(options = {}) {
    const dir = options.modulesDir || path.join(__dirname, 'ujg-ticket-assistant-modules');
    const parts = MODULE_ORDER.map(file => {
        const source = path.join(dir, file);
        if (!fs.existsSync(source)) throw new Error('Module not found: ' + file);
        // Existing embeddedAmdRenames matches JSON-quoted identifiers. Normalize this
        // dependency in our bundle without editing the reviewed shared/AI sources.
        return '/* === Module: ' + file + ' === */\n' + fs.readFileSync(source, 'utf8').trim()
            .replace(/'_ujgShared_llmClient'/g, '"_ujgShared_llmClient"');
    });
    const source = '// Auto-generated by build-ticket-assistant.js; edit source modules.\n' + parts.join('\n\n') +
        '\n\ndefine("_ujgTicketAssistant", ["_ujgTA_main"], function(G) { return G; });\n';
    if (options.write !== false) fs.writeFileSync(path.join(__dirname, 'ujg-ticket-assistant.js'), source);
    return source;
}
build.MODULE_ORDER = MODULE_ORDER.slice();
if (require.main === module) {
    build();
    const {buildAssets, resolveReleaseRef} = require('./build-widget-bootstrap-assets');
    const releaseRef = resolveReleaseRef();
    const assets = buildAssets({widgets: ['ujg-ticket-assistant'], releaseRef});
    for (const [file, source] of Object.entries(assets)) fs.writeFileSync(path.join(__dirname, file), source);
    console.log('Built ticket assistant only; releaseRef: ' + releaseRef);
}
module.exports = {build};
