#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
// AMD resolves dependencies after every definition has registered.
const MODULE_ORDER = ['transport.js', 'evidence.js', 'jira-api.js', 'confluence-api.js', 'tools.js', 'skills.js', 'chat.js', 'storage.js', 'ui.js', 'main.js'];
function build(options = {}) {
    const dir = options.modulesDir || path.join(__dirname, 'ujg-knowledge-assistant-modules');
    const parts = MODULE_ORDER.map(file => {
        const source = path.join(dir, file);
        if (!fs.existsSync(source)) throw new Error('Module not found: ' + file);
        // Shared bootstrap transforms match double-quoted identifiers. Keep this
        // compatibility normalization local to the new widget's source bundle.
        return '/* === Module: ' + file + ' === */\n' + fs.readFileSync(source, 'utf8').trim()
            .replace(/'_ujgShared_llmClient'/g, '"_ujgShared_llmClient"')
            .replace(/'_ujgKnowledgeAssistant'/g, '"_ujgKnowledgeAssistant"');
    });
    const picoPath = options.picoPath || path.join(__dirname, 'vendor/pico-1.4.0.amd.js');
    if (!fs.existsSync(picoPath)) throw new Error('Pico bundle not found: ' + picoPath);
    const pico = fs.readFileSync(picoPath, 'utf8').trim()
        .replace('"_ujgTA_picoRuntime"', '"_ujgKA_picoRuntime"');
    const source = '// Auto-generated by build-knowledge-assistant.js; edit source modules.\n' + pico + '\n\n' + parts.join('\n\n') + '\n';
    if (options.write !== false) fs.writeFileSync(path.join(__dirname, 'ujg-knowledge-assistant.js'), source);
    return source;
}
build.MODULE_ORDER = MODULE_ORDER.slice();
if (require.main === module) {
    build();
    const {buildAssets, resolveReleaseRef} = require('./build-widget-bootstrap-assets');
    const releaseRef = resolveReleaseRef();
    const assets = buildAssets({widgets: ['ujg-knowledge-assistant'], releaseRef});
    for (const [file, source] of Object.entries(assets)) fs.writeFileSync(path.join(__dirname, file), source);
    console.log('Built knowledge assistant only; releaseRef: ' + releaseRef);
}
module.exports = {build};
