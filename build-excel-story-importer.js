#!/usr/bin/env node

var fs = require("fs");
var path = require("path");

var MODULES_DIR = path.join(__dirname, "ujg-excel-story-importer-modules");
var SHARED_DIR = path.join(__dirname, "ujg-shared-modules");
var OUTPUT_FILE = path.join(__dirname, "ujg-excel-story-importer.js");

var MODULE_ORDER = [
  { dir: SHARED_DIR, file: "llm-client.js" },
  "config.js",
  "mapping-store.js",
  "description.js",
  "deadlines.js",
  "due-date-sync.js",
  "component-sync.js",
  "parser.js",
  "remark-id.js",
  "creator.js",
  "api.js",
  "excel-loader.js",
  "xlsx-patcher.js",
  "registry.js",
  "icons.js",
  "due-date-sync-ui.js",
  "column-preflight-ui.js",
  "teams.js",
  "teams-ui.js",
  "statistics.js",
  "statistics-ui.js",
  "activity.js",
  "activity-management-ui.js",
  "activity-ai.js",
  { dir: path.join(__dirname, "vendor"), file: "marked-16.4.2.umd.js", amd: "_ujgESI_marked" },
  "activity-markdown.js",
  "activity-ai-ui.js",
  "activity-ui.js",
  "grid.js",
  "rendering.js",
  "main.js",
];

function readModule(entry) {
  var dir = typeof entry === "object" && entry.dir ? entry.dir : MODULES_DIR;
  var fileName = typeof entry === "object" && entry.file ? entry.file : entry;
  var filePath = path.join(dir, fileName);
  if (!fs.existsSync(filePath)) throw new Error("Module not found: " + fileName);
  var source = fs.readFileSync(filePath, "utf8");
  if (entry.amd) {
    return 'define("' + entry.amd + '", [], function() {\nvar module = {exports:{}}, exports = module.exports;\n' + source + '\nreturn module.exports;\n});';
  }
  return source;
}

function build() {
  console.log("Building ujg-excel-story-importer.js from modules...");
  var parts = [
    "// Auto-generated file - DO NOT EDIT MANUALLY",
    "// Generated by build-excel-story-importer.js",
    "// To modify, edit files in ujg-excel-story-importer-modules/ and rebuild",
    "",
  ];
  MODULE_ORDER.forEach(function(entry) {
    var fileName = typeof entry === "object" && entry.file ? entry.file : entry;
    parts.push("/* === Module: " + fileName + " === */");
    parts.push(readModule(entry).trim());
    parts.push("");
  });
  parts.push('define("_ujgExcelStoryImporter", ["_ujgESI_main"], function(G) {');
  parts.push('  "use strict";');
  parts.push("  return G;");
  parts.push("});");
  parts.push("");
  fs.writeFileSync(OUTPUT_FILE, parts.join("\n"), "utf8");
}

build.MODULE_ORDER = MODULE_ORDER.map(function(entry) {
  return typeof entry === "object" && entry.file ? entry.file : entry;
});

if (require.main === module) build();

module.exports = { build: build };
